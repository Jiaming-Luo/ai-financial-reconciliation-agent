"""Generate bilingual advisory analysis from existing reconciliation reports."""

import argparse
import sys
from pathlib import Path

from src.context_builder import ContextError, build_context
from src.llm_analyzer import analyze, write_analysis
from src.llm_client import LLMError, create_provider
from src.output_validator import OutputValidationError


PROJECT_ROOT = Path(__file__).resolve().parent


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, default=PROJECT_ROOT / "outputs")
    parser.add_argument("--output-dir", type=Path, default=PROJECT_ROOT / "outputs")
    parser.add_argument("--language", choices=("en", "cn", "both"), default="en")
    parser.add_argument("--provider", choices=("mock", "openai", "qwen"), help="Defaults to LLM_PROVIDER or mock.")
    args = parser.parse_args(argv)
    try:
        context = build_context(args.input_dir)
        provider = create_provider(args.provider)
        languages = ("en", "cn") if args.language == "both" else (args.language,)
        reports = [analyze(context, provider, language) for language in languages]
        for report in reports:
            write_analysis(report, args.output_dir)
    except (ContextError, LLMError, OutputValidationError) as error:
        print(f"Analysis rejected: {error} No reports were generated by this run.", file=sys.stderr)
        return 1
    except OSError:
        print("Analysis report write failed. Check the output directory.", file=sys.stderr)
        return 1
    print(f"{provider.mode} analysis ({', '.join(languages)}) written to {args.output_dir}")
    omitted = sum(len(report["warnings"]) for report in reports)
    if omitted:
        print(f"Core analysis passed. Validation omitted {omitted} supplementary note(s).", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
